# superclass
from .Timestamp import Timestamp


# the earth received times
class ERT(Timestamp):
    """
    An Earth Received Time, in UTC: a timestamp generated by the receiving station on earth, an
    arbitrary downlink delay after the instrument acquired the data
    """

    # properties
    @property
    def doc(self):
        """
        Build my docstring
        """
        # fold my name in
        return f"the {self.name} earth received time"


